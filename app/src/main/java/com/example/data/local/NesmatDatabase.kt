abstract class NesmatDatabase : RoomDatabase() {
  abstract fun contentDao(): ContentDao
  abstract fun checkinDao(): CheckinDao
  abstract fun noteDao(): NoteDao
  abstract fun assessmentDao(): AssessmentDao
  abstract fun supportDao(): SupportDao
  abstract fun userPrefDao(): UserPrefDao
  abstract fun habitDao(): HabitDao

  companion object {
    @Volatile
    private var INSTANCE: NesmatDatabase? = null

    fun getDatabase(context: Context, scope: CoroutineScope): NesmatDatabase {
      return INSTANCE ?: synchronized(this) {
        val instance = Room.databaseBuilder(
          context.applicationContext,
          NesmatDatabase::class.java,
          "nesmat_alhayat.db"
        )
          .addCallback(DatabaseCallback(scope))
          .fallbackToDestructiveMigration()
          .build()
        INSTANCE = instance
        scope.launch(Dispatchers.IO) {
          populateInitialContent(instance.contentDao())
        }
        instance
      }
    }

    private class DatabaseCallback(
      private val scope: CoroutineScope
    ) : RoomDatabase.Callback() {
      override fun onCreate(db: SupportSQLiteDatabase) {
        super.onCreate(db)
        INSTANCE?.let { database ->
          scope.launch(Dispatchers.IO) {
            populateInitialContent(database.contentDao())
          }
        }
      }
    }

